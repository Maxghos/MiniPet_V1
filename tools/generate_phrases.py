"""Generate the flash-resident phrase bank from the user's UTF-8 text."""
import argparse
import json
from pathlib import Path

HEADINGS = {"Vida cotidiana", "Trabajo y productividad", "Tecnología", "Amor y relaciones", "Filosofía absurda"}
root = Path(__file__).resolve().parent.parent
source = root / "assets/frases_random_es.txt"
target = root / "include/RandomPhrases.h"
phrases = [line.strip() for line in source.read_text(encoding="utf-8-sig").splitlines()
           if line.strip() and line.strip() not in HEADINGS]
if len(phrases) != 100 or len(set(phrases)) != 100:
    raise SystemExit("Expected 100 distinct phrases; check the source file")
result = ('#pragma once\n// Generated by tools/generate_phrases.py; edit assets/frases_random_es.txt.\n'
          'namespace messages {\ninline constexpr const char* randomPhrases[] = {\n'
          + ''.join('    ' + json.dumps(phrase, ensure_ascii=False) + ',\n' for phrase in phrases)
          + '};\n}\n')
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
if args.check:
    if not target.exists() or target.read_text() != result:
        raise SystemExit("Phrase bank is stale: run python3 tools/generate_phrases.py")
else:
    target.write_text(result, encoding="utf-8")
print(f"Phrase bank: {len(phrases)} phrases verified")
